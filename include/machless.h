/*
 * machless — macOS in-memory Mach-O packer/loader built on ReflectiveLoader.
 *
 * Shared format and interface declarations for the packer and loaders.
 *
 * Changing the on-disk header layout requires a format version bump. The
 * header marker is deliberately a per-build profile value.
 */
#ifndef MACHLESS_H
#define MACHLESS_H

#include <stdint.h>
#include <stddef.h>
#include <string.h>

/* ── Identity ──────────────────────────────────────────────────── */

#ifndef ML_MAGIC
#define ML_MAGIC           0x4D41434Cu  /* generic templates only */
#endif
#define ML_FORMAT_VERSION  4u

/* A profile generated by machless-pack replaces ML_MAGIC for each final
 * artifact. The loader scans its non-executable, read-only sections instead
 * of carrying stable segment/section-name indicators. */

#define ML_FLAG_SPLIT_KEY  0x00000001u
#define ML_KNOWN_FLAGS     ML_FLAG_SPLIT_KEY

/* ── Cipher suite IDs (header.cipher_suite) ────────────────────── */

#define ML_CIPHER_NONE         0u  /* no encryption or authentication */
#define ML_CIPHER_AES256_GCM   1u  /* primary */
#define ML_CIPHER_CHACHA20_P   2u  /* ChaCha20-Poly1305, alternate */

/* ── Architecture slice descriptors (fat payload support) ──────── */

#define ML_ARCH_ARM64    0x0100000Cu  /* matches CPU_TYPE_ARM64 from mach/machine.h */
#define ML_ARCH_X86_64   0x01000007u  /* matches CPU_TYPE_X86_64 */

#define ML_MAX_SLICES    2u           /* arm64 and x86_64 */

/*
 * A slice descriptor lives inside the header. Each slice has an independent
 * (offset, size) into the ciphertext blob that follows the header. The CPU
 * type lets the loader choose the host-compatible slice before decryption.
 */
typedef struct {
    uint32_t cpu_type;          /* ML_ARCH_*, or 0 if unused */
    uint32_t ciphertext_offset; /* relative to first byte after header */
    uint32_t ciphertext_size;   /* payload bytes (ciphertext for AEAD) */
    uint32_t plaintext_size;    /* original payload size */
    uint8_t  tag[16];           /* AEAD tag; zero when cipher is NONE */
    uint8_t  iv[12];            /* per-slice random IV */
} ml_slice_t;

/* ── Pack header (on-disk, little-endian) ──────────────────────── */

typedef struct {
    uint32_t magic;             /* ML_MAGIC */
    uint16_t version;           /* ML_FORMAT_VERSION */
    uint16_t cipher_suite;      /* ML_CIPHER_* */
    uint32_t slice_count;       /* 1 (thin) or 2 (fat) */
    uint32_t flags;             /* ML_FLAG_* */

    /* Random per-container key. Final artifacts store key XOR profile mask. */
    uint8_t  master_key[32];

    ml_slice_t slices[ML_MAX_SLICES];

    uint8_t  reserved[24];       /* zero — bump version before using */
} ml_pack_header_t;

/* ── Compile-time sanity ───────────────────────────────────────── */

#ifdef __STDC_VERSION__
#if __STDC_VERSION__ >= 201112L
_Static_assert(sizeof(ml_pack_header_t) % 16 == 0,
               "pack header size must preserve packed-blob alignment");
_Static_assert(sizeof(ml_pack_header_t) == 160,
               "unexpected pack header layout");
#endif
#endif

/* ── AAD (Additional Authenticated Data) ───────────────────────── */

/*
 * AES-256-GCM and ChaCha20-Poly1305 feed this blob as AAD. Their tags cover
 * the selected header fields and the current slice's metadata, including the
 * cipher suite and slice layout.
 * ML_CIPHER_NONE performs no authentication.
 *
 * Excluded from AAD intentionally:
 *   master_key  — it is the encryption key itself
 *   slice.iv    — the IV is already mixed into the AEAD internally
 *   slice.tag   — the tag is the AEAD output, cannot cover itself
 */
typedef struct __attribute__((packed)) {
    uint32_t magic;
    uint16_t version;
    uint16_t cipher_suite;
    uint32_t slice_count;
    uint32_t flags;
    uint32_t cpu_type;
    uint32_t ciphertext_offset;
    uint32_t ciphertext_size;
    uint32_t plaintext_size;
    uint8_t  slice_index;
} ml_aad_t;

static inline void ml_build_aad(const ml_pack_header_t *hdr,
                                 const ml_slice_t       *slice,
                                 uint8_t                 idx,
                                 ml_aad_t               *out) {
    out->magic             = hdr->magic;
    out->version           = hdr->version;
    out->cipher_suite      = hdr->cipher_suite;
    out->slice_count       = hdr->slice_count;
    out->flags             = hdr->flags;
    out->cpu_type          = slice->cpu_type;
    out->ciphertext_offset = slice->ciphertext_offset;
    out->ciphertext_size   = slice->ciphertext_size;
    out->plaintext_size    = slice->plaintext_size;
    out->slice_index       = idx;
}

/* ── Public function prototypes ────────────────────────────────── */

/* Packer */
int  ml_pack_dylib(const char *input_dylib,
                   const char *output_packed,
                   uint16_t cipher_suite,
                   int raw, /* skip Mach-O validation — for wrapping .packed blobs */
                   uint32_t cpu_filter,
                   uint32_t marker,
                   const uint8_t key_mask[32]);

/* Loader */
int  ml_get_embedded_payload(const void *image_address,
                             const uint8_t **data, size_t *size);
int  ml_load_and_run(const uint8_t *packed_data, size_t packed_size,
                     char *const argv[], char *const envp[]);
const ml_pack_header_t *ml_find_header(const uint8_t *data, size_t size);

/* Crypto */
int  ml_decrypt_slice(const ml_pack_header_t *hdr,
                      const ml_slice_t *slice,
                      const uint8_t *ciphertext,
                      uint8_t *plaintext_out);
int  ml_encrypt_slice(ml_pack_header_t *hdr,
                      ml_slice_t *slice,
                      const uint8_t *plaintext, size_t plaintext_size,
                      uint8_t **ciphertext_out, size_t *ciphertext_size_out);

/* Mach-O utilities */
int  ml_is_macho_dylib(const uint8_t *data, size_t size);

/* Execution backend (ReflectiveLoader wrapper) */
int  ml_execute_from_memory(const uint8_t *macho, size_t size);

/* ── Debug logging (compile-out in release builds) ─────────────── */

#ifdef ML_DEBUG
#include <stdio.h>
#define ML_DBG(...) fprintf(stderr, "[machless] " __VA_ARGS__)
#else
#define ML_DBG(...) ((void)0)
#endif

#endif /* MACHLESS_H */
